import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { classifyStandardImportQuality } from './standard-import-quality.mjs';
import { unwrapPublishedOriginal } from '../standard-preprocessing/lib/original-section.mjs';
import { simplifyPublishedChinese } from '../standard-preprocessing/lib/chinese-script.mjs';
const root = path.resolve(process.argv[2]);
const result = JSON.parse(await fs.readFile(path.join(root,'result.json'),'utf8'));
const request = JSON.parse(await fs.readFile(path.join(root,'request.json'),'utf8'));
const publication = JSON.parse(await fs.readFile(path.join(root,'publication.json'),'utf8'));
const markdown = await fs.readFile(publication.markdown.path,'utf8');
const normalize = text => text.replace(/<[^>]+>/g,'').replace(/[^\p{L}\p{N}]/gu,'');
assert.equal(classifyStandardImportQuality(result).admissible,true);
assert.equal(result.receipt.cleaning_policy.include_reading_guide,false);
assert.equal(result.artifacts.semantic.judgments,null);
assert.deepEqual(result.artifacts.semantic.insights,[]);
assert.doesNotMatch(markdown,/^## (阅读前置卡|核心洞察|导读卡)$/m);
const original = unwrapPublishedOriginal(markdown.split('\n## 原文\n')[1] || (publication.duplicate_original_removed ? markdown.split('\n## 正文\n')[1] : null));
assert.ok(original);
assert.equal(normalize(original),normalize(simplifyPublishedChinese(request.material.markdown).markdown));
assert.equal(crypto.createHash('sha256').update(markdown).digest('hex'),publication.markdown.sha256);
assert.deepEqual(publication.failed_validations,result.receipt.validations.filter(item=>item.status==='failed'));
assert.ok(result.receipt.model.attempts.every(item => !item.usage?.stages?.semantic_calls));
const report = {passed:true,status:result.status,quality_status:publication.quality_status,published_path:publication.markdown.path,publication_sha256:publication.markdown.sha256,source_blocks:result.artifacts.cleaning_manifest.source_nodes.length,body_blocks:result.artifacts.body_blocks.length,original_complete:true,guide_api_calls:0,model_calls:result.receipt.model.calls,warnings_in_audit_only:true};
await fs.writeFile(path.join(root,'independent-publication-validation.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
